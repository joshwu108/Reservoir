# ---------------------------------------------------------------------------
# Adapter helpers: from a policy and a sampled batch to what gets written
# ---------------------------------------------------------------------------

class Placement(NamedTuple):
    """Which draws of a sampled batch are placed, declined, and with what advantage."""

    kept: list[int]           # draw positions placed, in draw order
    declined: list[int]       # draw positions declined, in draw order
    weighted: list[float]     # advantage written for each kept draw: reward * float(is_weight * scale)
    rescaled: int             # kept draws whose scale is below 1


def resolve_policy(
    staleness_policy: Union[StalenessPolicy, str, None], max_log_ratio: Optional[float],
    max_declines_per_step: Optional[int], telemetry: bool,
) -> StalenessPolicy:
    """The adapter's policy from its constructor arguments.

    ``staleness_policy`` is a ``StalenessPolicy``, a preset name or None;
    the legacy ``max_log_ratio`` and ``max_declines_per_step`` keywords fill
    the policy's stage 4 when it does not set them itself, and conflict
    otherwise. Stages 1 to 3 record their decisions in the telemetry
    record, so they need ``telemetry=True``; the legacy gate alone keeps
    working with telemetry off, as in 0.6.0 (its declines are then visible
    only in the batch witness).
    """
    if isinstance(staleness_policy, str):
        policy = StalenessPolicy.preset(staleness_policy)
    elif staleness_policy is None:
        policy = StalenessPolicy()
    elif isinstance(staleness_policy, StalenessPolicy):
        policy = staleness_policy
    else:
        raise TypeError(f"staleness_policy must be a StalenessPolicy, a preset name or None, got {type(staleness_policy).__name__}")
    for name, value in (("max_log_ratio", max_log_ratio), ("max_declines_per_step", max_declines_per_step)):
        if value is None:
            continue
        if getattr(policy, name) is not None:
            raise ValueError(f"{name} is set both as a keyword and on the staleness policy; set it in one place")
        policy = dataclasses.replace(policy, **{name: value})
    if policy.active and not policy.legacy_only and not telemetry:
        raise ValueError(
            "a staleness policy with an age bound, ESS floor or mass cap records its decisions in the telemetry "
            "record and needs telemetry=True; only the legacy max_log_ratio gate runs with telemetry off"
        )
    return policy


def place(rewards: Sequence[float], is_weights: Sequence[Fraction], decisions: Sequence[RowDecision]) -> Placement:
    """Fold the decisions into the kept and declined draws and the advantages to write.

    With no decisions (an inactive policy) every draw is kept with its
    importance-weighted advantage, exactly as before the policy existed.
    """
    n = len(rewards)
    if not decisions:
        return Placement(list(range(n)), [], [float(r) * float(w) for r, w in zip(rewards, is_weights)], 0)
    if len(decisions) != n:
        raise ValueError(f"{len(decisions)} decisions for {n} draws")
    kept = [d.draw for d in decisions if d.kept]
    declined = [d.draw for d in decisions if not d.kept]
    weighted = [float(rewards[d.draw]) * float(is_weights[d.draw] * d.scale) for d in decisions if d.kept]
    return Placement(kept, declined, weighted, sum(1 for d in decisions if d.kept and d.scale != 1))


def evictions_for(indices: Sequence[int], decisions: Sequence[RowDecision]) -> list[tuple[int, str]]:
    """``(slot, reason)`` for every buffer slot whose draws were all declined for an evicting reason.

    A slot drawn more than once is evicted only if no draw of it was kept;
    an ``ess`` decline never evicts (the batch, not the row, was the
    problem). When one slot was declined as both ``drift`` and ``age``,
    ``drift`` is recorded.
    """
    kept_slots = {indices[d.draw] for d in decisions if d.kept}
    reasons: dict[int, str] = {}
    for d in decisions:
        slot = indices[d.draw]
        if d.reason in EVICTING_REASONS and slot not in kept_slots:
            reasons[slot] = "drift" if "drift" in (reasons.get(slot), d.reason) else d.reason
    return sorted(reasons.items())


